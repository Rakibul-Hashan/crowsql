// SQL dump reader: quotes, comments, DELIMITER directives and session SQL modes.
export function detectCompatibility(sql,choice='auto'){
  if(choice==='sqlite'||choice==='auto'&&/^\s*--[^\n]*\b(?:tested on|generated by|dumped from|dialect\s*:)\s*SQLite\b/im.test(sql))return 'sqlite';
  return 'mysql';
}
export function importMode(base,choice,compatibility,zero){
  const notices=[];let modes=choice==='NONE'?base.split(',').filter(Boolean):[choice];
  if(choice==='MYSQL40'){modes=['HIGH_NOT_PRECEDENCE'];notices.push('MYSQL40 is no longer accepted by this engine. Applied its supported HIGH_NOT_PRECEDENCE behavior; other removed flags cannot be reproduced.')}
  if(compatibility==='sqlite'){modes.push('NO_BACKSLASH_ESCAPES','PIPES_AS_CONCAT');notices.push('SQLite learning-file compatibility enabled: literal backslashes and || string concatenation. Queries still run on MariaDB, not SQLite.')}
  if(zero)modes.push('NO_AUTO_VALUE_ON_ZERO');
  return {mode:[...new Set(modes)].join(','),notices};
}
export class SQLDumpReader{
  constructor(sql){this.sql=sql.replace(/^\uFEFF/,'');this.offset=0;this.line=1;this.delimiter=';'}
  next({noBackslashEscapes=false}={}){
    const s=this.sql;let start=this.offset,startLine=this.line,quote='',block=false,lineComment=false,executable=false;
    const take=()=>{if(s[this.offset]==='\n')this.line++;return s[this.offset++]};
    while(this.offset<s.length){
      const i=this.offset,c=s[i],n=s[i+1];
      if(!quote&&!block&&!lineComment&&(i===0||s[i-1]==='\n')){
        const m=s.slice(i).match(/^[ \t]*DELIMITER[ \t]+(\S+)[ \t]*(?:\r?\n|$)/i);
        if(m){if(executable)throw Error('DELIMITER directive encountered before the previous statement ended (line '+this.line+').');this.delimiter=m[1];for(let k=0;k<m[0].length;k++)take();start=this.offset;startLine=this.line;continue}
      }
      if(lineComment){take();if(c==='\n')lineComment=false;continue}
      if(block){take();if(c==='*'&&n==='/'){take();block=false}continue}
      if(quote){take();if(c==='\\'&&!noBackslashEscapes&&quote!=='`'&&this.offset<s.length){take();continue}if(c===quote){if(n===quote)take();else quote=''}continue}
      if(c==='-'&&n==='-'&&/\s/.test(s[i+2]||' ')||c==='#'){lineComment=true;take();if(c==='-')take();continue}
      if(c==='/'&&n==='*'){block=true;if(s[i+2]==='!'||s.slice(i+2,i+4)==='M!')executable=true;take();take();continue}
      if(s.startsWith(this.delimiter,i)){
        const end=i;for(let k=0;k<this.delimiter.length;k++)take();
        if(executable)return {sql:s.slice(start,end).trim(),start,line:startLine,end};
        start=this.offset;startLine=this.line;continue;
      }
      if(c==='\''||c==='"'||c==='`'){quote=c;executable=true;take();continue}
      if(!/\s/.test(c))executable=true;take();
    }
    if(executable)return {sql:s.slice(start).trim(),start,line:startLine,end:s.length,unclosed:quote||block};
    return null;
  }
}
export async function runSQLImport(engine,sql,{compatibility='auto',mode='NONE',zero=true,foreignKeys=true,skip=0,continueOnError=true,isCanceled=()=>false,onProgress=()=>{}}={}){
  const [previous]=await engine.query('SELECT @@SESSION.sql_mode AS mode, @@SESSION.foreign_key_checks AS fk');
  const selected=detectCompatibility(sql,compatibility),configuration=importMode(previous.mode,mode,selected,zero);
  const report={compatibility:selected,appliedMode:configuration.mode,notices:configuration.notices,attempted:0,succeeded:0,failed:0,skipped:0,warnings:[],errors:[],canceled:false,stopped:false};
  const reader=new SQLDumpReader(sql);let currentMode=configuration.mode,number=0;
  try{
    await engine.exec('SET SESSION sql_mode = ?',[currentMode]);await engine.exec('SET SESSION FOREIGN_KEY_CHECKS = '+(foreignKeys?'1':'0'));
    let item;
    while((item=reader.next({noBackslashEscapes:currentMode.split(',').includes('NO_BACKSLASH_ESCAPES')}))){
      number++;if(number<=skip){report.skipped++;continue}
      if(isCanceled()){report.canceled=true;break}
      report.attempted++;
      try{
        await engine.exec(item.sql);report.succeeded++;
        const warnings=await engine.query('SHOW WARNINGS');
        for(const w of warnings)report.warnings.push({statement:number,line:item.line,level:w.Level,code:w.Code,message:w.Message});
        // A dump can enable/restore SQL modes. Parse subsequent strings using that mode.
        if(/\bSQL_MODE\b/i.test(item.sql))currentMode=(await engine.query('SELECT @@SESSION.sql_mode AS mode'))[0].mode;
      }catch(e){
        report.failed++;report.errors.push({statement:number,line:item.line,sql:item.sql,message:e.message||String(e)});
        if(!continueOnError){report.stopped=true;break}
      }
      await onProgress(report,item,Math.min(100,Math.round(reader.offset/reader.sql.length*100)));
    }
  }finally{
    await engine.exec('SET SESSION sql_mode = ?',[previous.mode]);
    await engine.exec('SET SESSION FOREIGN_KEY_CHECKS = '+(previous.fk?'1':'0'));
  }
  return report;
}

// Resolve a server-level table dump without forcing an extra database setup step.
export function suggestedImportDatabase(filename='') {
  let name=filename.split(/[\\/]/).pop().replace(/\.gz$/i,'').replace(/\.(sql|txt)$/i,'').replace(/\s*\(\d+\)\s*$/,'').trim();
  name=name.normalize('NFKC').replace(/[^a-zA-Z0-9_]/g,'_').replace(/_+/g,'_').replace(/^_+|_+$/g,'').slice(0,64)||'imported_database';
  if (/^(mysql|sys|information_schema|performance_schema)$/i.test(name))name='imported_'+name;
  return name.slice(0,64);
}
export function resolveImportTarget(sql,{target='',selectedDatabase='',filename=''}={}) {
  if(target.trim())return {name:target.trim(),source:'explicit'};
  if(selectedDatabase)return {name:selectedDatabase,source:'selected'};
  const reader=new SQLDumpReader(sql);let item;
  while((item=reader.next({noBackslashEscapes:detectCompatibility(sql)==='sqlite'}))){
    // Only leading comments are removed; text inside SQL strings remains untouched.
    let head=item.sql;
    for(;;){const next=head.replace(/^\s*(?:--[^\n]*(?:\n|$)|#[^\n]*(?:\n|$)|\/\*[\s\S]*?\*\/)\s*/,'');if(next===head)break;head=next;}
    if(/^\s*(?:CREATE\s+(?:DATABASE|SCHEMA)|USE)\b/i.test(head))return {name:'',source:'dump'};
  }
  return {name:suggestedImportDatabase(filename),source:'filename'};
}
